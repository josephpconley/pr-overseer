class SoftApproval(unittest.TestCase):
    def info(self, meta, tier="deep"):
        return {"cfg": CFG, "meta": meta, "tier": tier}

    def test_reason_only_for_flagged_approve(self):
        self.assertIn("hard-risk path", rv.soft_approval_reason("APPROVE", self.info(RISKY), "", PR))
        self.assertIsNone(rv.soft_approval_reason("APPROVE", self.info(PLAIN), "", PR))          # not flagged
        self.assertIsNone(rv.soft_approval_reason("APPROVE", self.info(RISKY, "everyday"), "", PR))  # tier gate
        self.assertIsNone(rv.soft_approval_reason("APPROVE", self.info(RISKY), "", DEP))           # Dependabot
        self.assertIsNone(rv.soft_approval_reason("REQUEST_CHANGES", self.info(RISKY), "", PR))    # stays formal
        self.assertIsNone(rv.soft_approval_reason("APPROVE", {}, "", PR))                          # tiers off

    def test_reason_ignores_once_per_pr_marker(self):
        with mock.patch.object(rv, "human_marker_path", side_effect=AssertionError("must not consult marker")):
            self.assertIsNotNone(rv.soft_approval_reason("APPROVE", self.info(RISKY), "", PR))

    def test_reason_fails_closed(self):
        with mock.patch.object(rv, "human_review_decision", side_effect=RuntimeError("boom")):
            self.assertIn("fail closed", rv.soft_approval_reason("APPROVE", self.info(RISKY), "", PR))

    def test_submit_soft_is_comment_not_approve(self):
        with mock.patch.object(rv, "run", return_value=cp()) as m:
            ok, detail = rv.submit_github_review("o/r", 7, "APPROVE", "Looks fine.\n\nVERDICT: APPROVE", soft_why="infra")
        cmd = m.call_args[0][0]
        self.assertTrue(ok); self.assertIn("soft APPROVE", detail)
        self.assertIn("--comment", cmd); self.assertNotIn("--approve", cmd); self.assertNotIn("--request-changes", cmd)
        body = cmd[cmd.index("--body") + 1]
        self.assertTrue(body.startswith(rv.SOFT_APPROVAL_MARKER))
        self.assertIn("pending human review", body); self.assertIn("human reviewer must give the actual approval", body)
        self.assertNotIn("VERDICT: APPROVE\n", body.split("\n\n", 1)[1])   # harness verdict line stripped

    def test_submit_unflagged_unchanged(self):
        with mock.patch.object(rv, "run", return_value=cp()) as m:
            self.assertEqual(rv.submit_github_review("o/r", 7, "APPROVE", "ok\n\nVERDICT: APPROVE"), (True, "APPROVE"))
            self.assertIn("--approve", m.call_args[0][0])
            self.assertEqual(rv.submit_github_review("o/r", 7, "REQUEST_CHANGES", "no\n\nVERDICT: REQUEST_CHANGES",
                                                     soft_why="infra"), (True, "REQUEST_CHANGES"))
            self.assertIn("--request-changes", m.call_args[0][0])

    def test_own_pr_comment_keeps_header_and_adds_note(self):
        with mock.patch.object(rv, "run", return_value=cp()) as m:
            rv.post_review_comment("o/r", 7, "APPROVE", "ok\n\nVERDICT: APPROVE", reviewed_sha="a" * 40, soft_why="infra")
        body = m.call_args[0][0][m.call_args[0][0].index("--body") + 1]
        self.assertEqual(rv.SELF_VERDICT_RE.match(body).group(1), "APPROVE")   # gate / duplicate skip still parse it
        self.assertTrue(body.startswith(rv.SELF_REVIEW_MARKER))
        self.assertIn("Soft approval", body)

    def test_already_reviewed_gates_recognise_soft_approval(self):
        # A soft approval is a COMMENTED review by the login.
        data = {"reviews": [{"author": {"login": "me"}, "state": "COMMENTED", "submittedAt": "2026-11-18T10:00:00Z",
                             "body": rv.SOFT_APPROVAL_MARKER + " — VERDICT: APPROVE (pending human review)**"}],
                "comments": [], "commits": [], "headRefOid": "abc"}
        with mock.patch.object(rv, "run", return_value=cp(0, json.dumps(data))):
            self.assertIn("already has your review (COMMENTED", rv.existing_review_by("o/r", 7, "me"))
            st = rv.fetch_feedback_state("o/r", 7, "me")
        act, why = rv.self_review_gate(st, {"attempts": []}, address_feedback=True, explicit_fix=False,
                                       max_fix=2, force=False)
        self.assertEqual(act, "skip", why)


class ReviewOneIntegration(base.Base):
    """review_one with everything mocked: which GitHub call does a flagged / unflagged review make?"""
    def run_one(self, meta, mode="review", own=None, flag_mock=None):
        def fake_tier(repo, number, hpath, *, diff, override, info=None, use_cache=True):
            if info is not None:
                info.update({"cfg": CFG, "meta": meta, "tier": "deep"})
            return "tier=deep"
        if own is None:
            own = (mode == "self_review")
        pr = base.PR if own else dict(base.PR, author={"login": "someone-else"})
        fm = flag_mock if flag_mock is not None else mock.Mock(return_value=None)
        with mock.patch.object(rv, "apply_tier_for_pr", side_effect=fake_tier), \
             mock.patch.object(rv, "flag_for_human_review", fm), \
             mock.patch.object(rv, "fetch_pr_authoring", return_value={}), \
             mock.patch.object(rv, "detect_latest_commit_harness", return_value=([], {})):
            out, err = io.StringIO(), io.StringIO()
            with redirect_stdout(out), redirect_stderr(err):
                rv.review_one("example-org/example-repo", self.tmp, pr, rv.load_json(self.hpath), self.hpath,
                              mode=mode, login=base.LOGIN, merge_on_approve=True)
        return out.getvalue() + err.getvalue()

    def test_flagged_other_author_approve_not_posted_emailed_instead(self):
        fm = mock.Mock(return_value=None)
        with mock.patch.object(rv, "submit_github_review") as submit, \
             mock.patch.object(rv, "post_review_comment") as post:
            log = self.run_one(RISKY, mode="review", own=False, flag_mock=fm)
        submit.assert_not_called()
        post.assert_not_called()
        self.assertIn("not posting APPROVE review on GitHub", log)
        kw = fm.call_args.kwargs
        self.assertTrue(kw["review_withheld"])
        self.assertIn("Looks fine.", kw["review_body"])

    def test_flagged_other_author_request_changes_not_posted(self):
        self.verdict_out = "### Blocking\n- Bad bug.\n\nVERDICT: REQUEST_CHANGES\n"
        fm = mock.Mock(return_value=None)
        with mock.patch.object(rv, "submit_github_review") as submit, \
             mock.patch.object(rv, "post_review_comment") as post:
            log = self.run_one(RISKY, mode="review", own=False, flag_mock=fm)
        submit.assert_not_called()
        post.assert_not_called()
        self.assertIn("not posting REQUEST_CHANGES review on GitHub", log)
        kw = fm.call_args.kwargs
        self.assertTrue(kw["review_withheld"])
        self.assertIn("Bad bug.", kw["review_body"])

    def test_flagged_own_pr_review_mode_is_soft(self):
        seen = {}
        def submit(repo, n, verdict, body, soft_why=None):
            seen.update(verdict=verdict, soft_why=soft_why); return True, "x"
        with mock.patch.object(rv, "submit_github_review", side_effect=submit):
            log = self.run_one(RISKY, mode="review", own=True)
        self.assertEqual(seen["verdict"], "APPROVE"); self.assertIn("hard-risk path", seen["soft_why"])
        self.assertIn("soft approval", log)

    def test_unflagged_approve_is_formal(self):
        seen = {}
        def submit(repo, n, verdict, body, soft_why=None):
            seen.update(verdict=verdict, soft_why=soft_why); return True, "x"
        with mock.patch.object(rv, "submit_github_review", side_effect=submit):
            self.run_one(PLAIN, mode="review", own=False)
        self.assertEqual(seen["verdict"], "APPROVE"); self.assertIsNone(seen["soft_why"])

    def test_flagged_self_review_keeps_merge_hold(self):
        # own PR + flagged: soft note in the comment, and the merge is still held (hold_merge)
        seen = {}
        def post(repo, n, verdict, body, reviewed_sha=None, soft_why=None):
            seen["soft_why"] = soft_why; return True, "COMMENT"
        flag_rec = {"reasons": ["hard-risk path"]}
        fm = mock.Mock(return_value=flag_rec)
        with mock.patch.object(rv, "post_review_comment", side_effect=post), \
             mock.patch.object(rv, "fetch_ci_status", return_value=base.ci_status(base.GREEN)):
            with mock.patch.object(rv, "apply_tier_for_pr") as at, \
                 mock.patch.object(rv, "flag_for_human_review", fm), \
                 mock.patch.object(rv, "fetch_pr_authoring", return_value={}), \
                 mock.patch.object(rv, "detect_latest_commit_harness", return_value=([], {})):
                at.side_effect = lambda *a, info=None, **k: (info.update({"cfg": CFG, "meta": RISKY, "tier": "deep"}), "t")[1]
                out = io.StringIO()
                with redirect_stdout(out), redirect_stderr(out):
                    rv.review_one("example-org/example-repo", self.tmp, base.PR, rv.load_json(self.hpath), self.hpath,
                                  mode="self_review", login=base.LOGIN, merge_on_approve=True)
        self.assertIsNotNone(seen["soft_why"])
        self.assertEqual(self.merges(), [])
        self.assertIn("merge held", out.getvalue())
        self.assertFalse(fm.call_args.kwargs["review_withheld"])
        self.assertIn("Looks fine.", fm.call_args.kwargs["review_body"])


