class Scrub(unittest.TestCase):
    def test_body_drops_overseer_and_attribution_lines(self):
        body = ("Fixes the flaky wait.\n\nGenerated by the PR overseer\n🤖 Generated with Claude Code\n"
                "Co-authored-by: Claude <noreply@anthropic.com>\nAutomated by pr-overseer.\n\n\n\nSee docs.\n")
        out = rv.scrub_pr_body(body)
        self.assertEqual(out, "Fixes the flaky wait.\n\nSee docs.\n")
        self.assertNotRegex(out, r"(?i)overseer|claude|generated")

    def test_body_keeps_normal_prose_about_generated_code(self):
        txt = "Generated code is regenerated by `make gen`.\nCreated by the migration.\n"
        self.assertEqual(rv.scrub_pr_body(txt), txt)

    def test_title(self):
        for raw, want in [("[overseer] test: weekly refactor", "test: weekly refactor"),
                          ("fix: thing (by overseer)", "fix: thing"),
                          ("Overseer: fix thing", "fix thing"),
                          ("fix thing - generated by Claude", "fix thing"),
                          ("fix the PR overseer lock", "fix lock"),
                          ("plain title", "plain title")]:
            got = rv.scrub_pr_title(raw)
            self.assertEqual(got, want, raw)
            self.assertNotIn("overseer", got.lower())
        self.assertEqual(rv.scrub_pr_title("Overseer", "Update"), "Update")

    def test_sanitize_none_passthrough(self):
        self.assertEqual(rv.sanitize_pr_text(None, None), (None, None))
        self.assertEqual(rv.sanitize_pr_text("t", None), ("t", None))


class Guard(unittest.TestCase):
    def test_pr_create_scrubs_before_gh(self):
        with mock.patch.object(rv, "run", return_value=cp(0, "https://x/pull/1")) as m:
            rv.gh_pr_create("o/r", base="main", head="b", title="[overseer] test: x",
                            body="Body\nGenerated by pr-overseer\nmore\n")
        cmd = m.call_args[0][0]
        self.assertEqual(cmd[:3], ["gh", "pr", "create"])
        self.assertEqual(cmd[cmd.index("--title") + 1], "test: x")
        self.assertEqual(m.call_args[1]["input_text"], "Body\nmore\n")
        self.assertNotIn("overseer", " ".join(cmd).lower())

    def test_pr_edit_scrubs_before_gh(self):
        with mock.patch.object(rv, "run", return_value=cp()) as m:
            rv.gh_pr_edit("o/r", 5, title="Overseer fix", body="a\nthe overseer did it\n")
        cmd = m.call_args[0][0]
        self.assertEqual(cmd[:4], ["gh", "pr", "edit", "5"])
        self.assertEqual(cmd[cmd.index("--title") + 1], "fix")
        self.assertEqual(m.call_args[1]["input_text"], "a\n")

    def test_no_raw_pr_create_or_edit_outside_the_guards(self):
        """Every gh pr create / edit must go through gh_pr_create / gh_pr_edit."""
        pat = re.compile(r"""["']pr["']\s*,\s*["'](create|edit)["']""")
        for name in ("review.py", "testrefactor.py"):
            for i, line in enumerate((HERE / name).read_text().splitlines(), 1):
                if pat.search(line):
                    self.assertTrue(name == "review.py" and ("gh_pr_create" in
                                    "\n".join((HERE / name).read_text().splitlines()[max(0, i - 8):i])
                                    or "gh_pr_edit" in "\n".join((HERE / name).read_text().splitlines()[max(0, i - 10):i])),
                                    f"raw gh pr create/edit at {name}:{i}")

    def test_prompts_carry_the_rule(self):
        fb = {"body": "x", "source": "review", "at": "t"}
        p = rv.build_fix_prompt("o/r", {"number": 1, "title": "t", "url": "u"}, "b", fb, "ctx", "diff")
        self.assertIn(rv.NO_SELF_MENTION_RULE, p)
        p2 = rv.build_dependabot_fix_prompt("o/r", {"number": 1}, "ci", ["."])
        self.assertIn(rv.NO_SELF_MENTION_RULE, p2)
        c = {"file": "a.test.ts", "suggested": "REBUILD", "cost_s": 5.0, "local_s": 4.0, "ci_s": 5.0, "tests": 3,
             "skipped": 0, "reasons": ["r"], "hints": ["h"], "slow_tests": [("slow", 3.0, 4.0)], "low_impact": 0,
             "flaky": False, "local": True, "score": 1}
        ci = {"days": 21, "branch": "main", "test_steps": [], "jobs": []}
        p3 = ttr.tr.build_prompt("o/r", "main", [c], ci, dict(ttr.tr.DEFAULTS))
        self.assertIn(rv.NO_SELF_MENTION_RULE, p3)

    def test_testrefactor_body_clean_even_if_harness_summary_mentions_overseer(self):
        c = {"file": "a.test.ts", "suggested": "REBUILD", "cost_s": 5.0, "local_s": 4.0, "ci_s": 5.0, "tests": 3,
             "skipped": 0, "reasons": [], "hints": [], "slow_tests": [], "low_impact": 0, "flaky": False,
             "local": True, "score": 1}
        ci = {"days": 21, "branch": "main", "test_steps": [], "jobs": []}
